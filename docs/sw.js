// Service worker: caches the small app shell so the Store app opens instantly
// and shows a friendly offline page instead of a blank window.
// The planner itself (Streamlit) is never cached — it always needs fresh data.
const CACHE = "utsav-shell-v1";
const SHELL = ["./", "./index.html", "./offline.html", "./favicon.png", "./icons/icon-192.png"];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  // Remove old cache versions so updates roll out cleanly.
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== "GET" || url.origin !== self.location.origin) return; // let Streamlit pass through
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(event.request, copy));
        return response;
      })
      .catch(() => caches.match(event.request).then((hit) => hit || caches.match("./offline.html")))
  );
});
